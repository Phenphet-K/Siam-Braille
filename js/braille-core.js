// 1. Unicode Braille Helper Utilities (U+2800 .. U+28FF)
// จุด 1-6 มีค่าบิต: dot 1 = 1, dot 2 = 2, dot 3 = 4, dot 4 = 8, dot 5 = 16, dot 6 = 32
export function dotsToUnicode(dots) {
  if (!dots || dots.length === 0) return '\u2800'; // blank cell
  let mask = 0;
  for (const d of dots) {
    if (d >= 1 && d <= 6) {
      mask |= (1 << (d - 1));
    }
  }
  return String.fromCharCode(0x2800 + mask);
}

export function unicodeToDots(char) {
  const code = char.charCodeAt(0);
  if (code < 0x2800 || code > 0x28FF) return [];
  const mask = code - 0x2800;
  const dots = [];
  for (let i = 1; i <= 6; i++) {
    if (mask & (1 << (i - 1))) {
      dots.push(i);
    }
  }
  return dots;
}

